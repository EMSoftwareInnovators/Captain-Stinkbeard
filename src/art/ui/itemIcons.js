export function buildItemIcons() {
  const out = {};
  for (const [name, def] of Object.entries(ICONS)) {
    out[`icon_${name}`] = new PixelCanvas(16, 16).stamp(def.rows, 0, 0, def.colors);
  }
  return out;
}

